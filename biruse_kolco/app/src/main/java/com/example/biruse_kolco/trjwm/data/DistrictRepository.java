    private static DistrictItem d(String id, String name, String subtitle, String history,
                                  List<String> facts, List<String> photos,
                                  String coatOfArms, int accentColor) {
        String summary = name + " — " + subtitle;
        return new DistrictItem(id, name, subtitle, summary, history, facts, photos, coatOfArms, accentColor);
    }

    private static List<String> facts(String... items) {
        return Collections.unmodifiableList(Arrays.asList(items));
    }

    private static List<String> photos(String... items) {
        return Collections.unmodifiableList(Arrays.asList(items));
    }
