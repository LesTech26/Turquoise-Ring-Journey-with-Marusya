    public static List<DistrictItem> getDistricts() {
        return DISTRICTS;
    }

    public static DistrictItem getDistrict(String id) {
        for (DistrictItem district : DISTRICTS) {
            if (district.getId().equals(id)) {
                return district;
            }
        }
        return DISTRICTS.get(0);
    }

